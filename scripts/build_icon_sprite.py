#!/usr/bin/env python
"""Build app/static/icons/lucide-sprite.svg from the icons the templates use.

Why this exists
---------------
The sprite used to be a verbatim copy of ``lucide-static/sprite.svg`` — all ~1,770
symbols, 477 KB — while the templates reference 60-odd of them. Every visitor
downloaded 95% dead weight. This script derives the symbol list from the templates
themselves, so the sprite can never drift out of sync with the UI: add an icon to a
template, re-run the script, and it is in the sprite. Remove the last reference and
the next run drops it.

Usage
-----
    npm install                 # provides node_modules/lucide-static
    python scripts/build_icon_sprite.py
    python scripts/build_icon_sprite.py --check   # verify, don't write (CI use)

``--check`` exits 1 when the committed sprite is stale, so CI fails loudly instead
of shipping a broken ``<use>`` reference.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
TEMPLATE_DIR = BASE_DIR / "app" / "templates"
ICON_SOURCE_DIR = BASE_DIR / "node_modules" / "lucide-static" / "icons"
SPRITE_PATH = BASE_DIR / "app" / "static" / "icons" / "lucide-sprite.svg"

# Any quoted argument inside an icon(...) call, e.g. icon('target') and
# icon(category_icons.get(c, 'briefcase-business')) both resolve to icon names.
ICON_CALL = re.compile(r"\bicon\(([^)]*)\)")
# Values in a dict literal whose keys look like taxonomy names, e.g. the
# category -> icon map on the home page: {'Engineering': 'code', ...}
DICT_ICON_VALUE = re.compile(r"""['"][^'"]+['"]\s*:\s*(['"])([a-z0-9-]+)\1""")

QUOTED = re.compile(r"""(['"])([a-z][a-z0-9-]*)\1""")
SVG_OPEN = re.compile(r"<svg\b[^>]*>", re.S)
SVG_ATTR = re.compile(r"""(\w[\w:-]*)\s*=\s*"([^"]*)\"""")
SVG_CLOSE = re.compile(r"</svg\s*>", re.I)

# Strings that appear inside an icon(...) call but are not icon names:
#   * the optional second argument is a size class from the `.icon-*` family;
#   * the flash banner picks its glyph with a ternary whose *condition* compares
#     against Flask's category names, e.g.
#     icon('circle-check' if category == 'success' else ..., 'icon-sm').
IGNORED_TOKENS = {"icon", "icon-xs", "icon-sm", "icon-lg", "success", "error"}


def referenced_icon_names() -> set[str]:
    """Every Lucide icon name referenced anywhere under app/templates."""
    names: set[str] = set()
    for template in sorted(TEMPLATE_DIR.rglob("*.html")):
        text = template.read_text(encoding="utf-8")
        for body in ICON_CALL.findall(text):
            names.update(m.group(2) for m in QUOTED.finditer(body))
        for match in DICT_ICON_VALUE.finditer(text):
            names.add(match.group(2))
    return names - IGNORED_TOKENS


def _reindent(markup: str) -> str:
    """Put each child element on its own line so the sprite diffs readably."""
    return re.sub(r">\s*<", ">\n<", markup.strip())


def _inner_svg(source: str) -> tuple[str, str]:
    """Return (viewBox, inner markup) from a Lucide icon file.

    Only the wrapper ``<svg>`` is removed; the child geometry is what the symbol
    is made of and must be kept verbatim.
    """
    open_tag = SVG_OPEN.search(source)
    if not open_tag:
        raise ValueError("no <svg> element found")
    close_tag = SVG_CLOSE.search(source, open_tag.end())
    if not close_tag:
        raise ValueError("no closing </svg> found")
    attrs = dict(SVG_ATTR.findall(open_tag.group(0)))
    inner = source[open_tag.end():close_tag.start()].strip()
    if not inner:
        raise ValueError("icon has no geometry")
    return attrs.get("viewbox", "0 0 24 24"), _reindent(inner)


def build_sprite(names: set[str]) -> str:
    missing = sorted(n for n in names if not (ICON_SOURCE_DIR / f"{n}.svg").exists())
    if missing:
        raise SystemExit(
            "These icons are referenced by a template but do not exist in "
            f"lucide-static:\n  {chr(10).join('  ' + m for m in missing)}\n"
            "Run `npm install`, or fix the typo in the template."
        )

    parts = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- @license lucide-static - ISC. Generated by scripts/build_icon_sprite.py"
        " - do not edit by hand. -->",
        '<svg xmlns="http://www.w3.org/2000/svg" version="1.1">',
        "  <defs>",
    ]
    for name in sorted(names):
        view_box, inner = _inner_svg(
            (ICON_SOURCE_DIR / f"{name}.svg").read_text(encoding="utf-8")
        )
        parts.append(f'    <symbol id="{name}" viewBox="{view_box}">')
        parts.append("      " + inner.replace("\n", "\n      "))
        parts.append("    </symbol>")
    parts.extend(["  </defs>", "</svg>", ""])
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the committed sprite is stale")
    args = parser.parse_args()

    if not ICON_SOURCE_DIR.is_dir():
        print(f"error: {ICON_SOURCE_DIR} not found — run `npm install` first.",
              file=sys.stderr)
        return 2

    names = referenced_icon_names()
    if not names:
        print("error: no icons referenced; refusing to write an empty sprite.",
              file=sys.stderr)
        return 2

    sprite = build_sprite(names)

    if args.check:
        current = SPRITE_PATH.read_text(encoding="utf-8") if SPRITE_PATH.exists() else ""
        if current != sprite:
            print(f"error: {SPRITE_PATH.relative_to(BASE_DIR)} is stale. "
                  "Run: python scripts/build_icon_sprite.py", file=sys.stderr)
            return 1
        print(f"icon sprite is up to date ({len(names)} symbols)")
        return 0

    SPRITE_PATH.write_text(sprite, encoding="utf-8")
    size_kb = SPRITE_PATH.stat().st_size / 1024
    print(f"wrote {SPRITE_PATH.relative_to(BASE_DIR)}: "
          f"{len(names)} symbols, {size_kb:.1f} KB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
